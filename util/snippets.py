import subprocess
from html import escape
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent


def main():
    output = ROOT / "target/doc/snippets"
    output.mkdir(parents=True, exist_ok=True)
    links = []
    with TemporaryDirectory(prefix="competitive-snippets-") as temporary:
        cache = Path(temporary) / "snippets.cache"
        subprocess.run(
            [
                "cargo",
                "codesnip",
                "--source-config=.github/workflows/codesnip.toml",
                "cache",
                str(cache),
            ],
            cwd=ROOT,
            check=True,
        )
        command = ["cargo", "codesnip", f"--use-cache={cache}"]
        names = subprocess.check_output([*command, "list"], cwd=ROOT, text=True).split()
        for name in names:
            code = subprocess.check_output([*command, "bundle", name], cwd=ROOT)
            (output / f"{name}.txt").write_bytes(code)
            links.append(f'<li><a href="{quote(name)}.txt">{escape(name)}</a></li>')

    (output / "index.html").write_text(
        """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Library snippets</title>
</head>
<body>
  <main>
    <h1>Library snippets</h1>
    <p><a href="../competitive/index.html">Documentation</a></p>
    <p>Generated by <a href="https://github.com/to-omer/codesnip">codesnip</a>
      with dependencies. Tests and formal verification code are excluded.</p>
    <ul>
"""
        + "\n".join(links)
        + "\n    </ul>\n  </main>\n</body>\n</html>\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
